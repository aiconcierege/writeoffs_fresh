-- Reference data is readable by signed-in users and is written only by the
-- service role or migrations.
alter table public.categories enable row level security;
alter table public.rulesets enable row level security;

drop policy if exists "categories_read_authenticated" on public.categories;
create policy "categories_read_authenticated"
  on public.categories for select
  to authenticated
  using (true);

